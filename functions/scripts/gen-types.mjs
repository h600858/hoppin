// Generates TypeScript from shared/schema. Run with: npm run gen:types
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { compile } from "json-schema-to-typescript";

const schemaDir = resolve(import.meta.dirname, "..", "..", "shared", "schema");
const outDir = resolve(import.meta.dirname, "..", "src", "generated");
const banner = "// GENERATED by scripts/gen-types.mjs from shared/schema. Do not edit.\n";

const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();
const schemas = files.map((f) => JSON.parse(readFileSync(join(schemaDir, f), "utf8")));
const common = schemas.find((s) => s.title === "CommonDefinitions");
const models = schemas.filter((s) => s !== common);

const options = {
  bannerComment: "",
  cwd: schemaDir,
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  $refOptions: { resolve: { http: false } },
};

const parts = [await compile(common, common.title, { ...options, unreachableDefinitions: true })];
for (const schema of models) {
  parts.push(await compile(schema, schema.title, { ...options, declareExternallyReferenced: false }));
}

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "types.ts"), banner + "\n" + parts.join("\n"));
writeFileSync(
  join(outDir, "schemas.ts"),
  banner + "\nexport const schemas = " + JSON.stringify(schemas, null, 2) + " as const;\n",
);
console.log(`Generated types for ${files.length} schemas.`);