// Generates TypeScript from shared/schema. Run with: npm run gen:types
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { compile } from "json-schema-to-typescript";

const schemaDir = resolve(import.meta.dirname, "..", "..", "shared", "schema");
const outDir = resolve(import.meta.dirname, "..", "src", "generated");
const banner = "// GENERATED by scripts/gen-types.mjs from shared/schema. Do not edit.\n";

const files = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".schema.json") || f === "callables.json")
  .sort();
const schemas = files.map((f) => JSON.parse(readFileSync(join(schemaDir, f), "utf8")));
// Files without a root type only hold $defs (common.schema.json, callables.json).
const definitionFiles = schemas.filter((s) => s.type === undefined);
const models = schemas.filter((s) => s.type !== undefined);
const fileOf = (schema) => new URL(schema.$id).pathname.slice(1);

// One root schema that points at every definition and every model.
// Compiling it in one go gives each named type (title) exactly once.
const root = {
  $id: "https://schema.innhopp.no/all.schema.json",
  title: "AllSchemas",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries([
    ...definitionFiles.flatMap((schema) =>
      Object.keys(schema.$defs).map((name) => [name, { $ref: `${fileOf(schema)}#/$defs/${name}` }]),
    ),
    ...models.map((schema) => [schema.title, { $ref: fileOf(schema) }]),
  ]),
};

const types = await compile(root, root.title, {
  bannerComment: "",
  cwd: schemaDir,
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  $refOptions: { resolve: { http: false } },
});

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "types.ts"), banner + "\n" + types);
writeFileSync(
  join(outDir, "schemas.ts"),
  banner + "\nexport const schemas = " + JSON.stringify(schemas, null, 2) + " as const;\n",
);
console.log(`Generated types for ${files.length} schemas.`);
